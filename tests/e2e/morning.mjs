import { chromium, devices } from "playwright-core";
import { spawn } from "node:child_process";
const srv = spawn("npx", ["vite", "preview", "--port", "4176", "--strictPort"], { stdio: "ignore" });
await new Promise((r) => setTimeout(r, 2500));
const fails = []; const ok = (c, m) => { console.log((c ? "PASS " : "FAIL ") + m); if (!c) fails.push(m); };
const b = await chromium.launch({ executablePath: process.env.CHROMIUM || "/usr/bin/chromium", args: ["--no-sandbox"] });
const page = await (await b.newContext({ ...devices["iPhone 13"] })).newPage();
const errs = []; page.on("pageerror", (e) => errs.push(e.message));
await page.route("**/fonts.g*/**", (r) => r.abort());
await page.goto("http://localhost:4176/"); await page.waitForSelector("#nav button", { state: "attached" });
for (let i = 0; i < 4 && await page.locator('[data-act="wnext"]').count(); i++) await page.click('[data-act="wnext"]');
if (await page.locator('[data-act="wdone"]').count()) await page.click('[data-act="wdone"]');
await page.evaluate(() => document.querySelector('[data-go="practice"]').click()); await page.waitForTimeout(300);
await page.evaluate(() => { const b = document.createElement("button"); b.dataset.act = "exstart"; b.dataset.id = "morning"; document.body.appendChild(b); b.click(); });
await page.waitForTimeout(300);
ok((await page.textContent("main")).includes("First, a safety note"), "first screen is the safety note");
await page.screenshot({ path: "shots/07-morning-safety.png" });
ok(errs.length === 0, "no page errors" + (errs[0] ? ": " + errs[0] : ""));
await b.close(); srv.kill(); process.exit(fails.length ? 1 : 0);
