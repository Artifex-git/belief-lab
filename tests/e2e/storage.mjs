import { chromium, devices } from "playwright-core";
import { spawn } from "node:child_process";
const srv = spawn("npx", ["vite", "preview", "--port", "4187", "--strictPort"], { stdio: "ignore" });
await new Promise((r) => setTimeout(r, 2500));
const fails = []; const ok = (c, m) => { console.log((c ? "PASS " : "FAIL ") + m); if (!c) fails.push(m); };
const b = await chromium.launch({ executablePath: process.env.CHROMIUM || "/usr/bin/chromium", args: ["--no-sandbox"] });
const ctx = await b.newContext({ ...devices["iPhone 13"] });
const page = await ctx.newPage();
const errs = []; page.on("pageerror", (e) => errs.push(e.message));
await page.route("**/fonts.g*/**", (r) => r.abort());
const open = async () => { await page.goto("http://localhost:4187/"); await page.waitForSelector("#nav button", { state: "attached" }); await page.waitForTimeout(600); };
const count = () => page.evaluate(() => window.BL.store.items.filter((x) => x.belief_raw === "I never rest").length);
await open();
await page.evaluate(() => window.BL.put({ _id: "profile", kind: "profile", onboarded: true, created_at: 1 }));
await page.evaluate(() => window.BL.put({ kind: "entry", mode: "thought", created_at: Date.now(), belief_raw: "I never rest" }));
await page.waitForTimeout(400);
await open(); ok(await count() === 1, "entry is still there after closing and reopening");
await page.evaluate(() => { localStorage.removeItem("bl-items"); localStorage.removeItem("bl-items-at"); });
await open(); ok(await count() === 1, "entry survives even if the quick copy is lost (restored from IndexedDB)");
ok(await page.evaluate(() => !!localStorage.getItem("bl-items")), "quick copy is rebuilt");
await page.evaluate(() => document.querySelector("#me").click()); await page.waitForTimeout(300);
const txt = await page.textContent("#data-line"); ok(/saved item/.test(txt), "You shows the data line: " + txt.slice(0, 60));
await page.evaluate(() => { const a = document.querySelector('[data-act="wipe"]'); a.click(); });
ok((await page.textContent('[data-act="wipe"]')).includes("again"), "delete needs a second tap");
await page.evaluate(() => document.querySelector('[data-act="wipe"]').click());
await page.waitForTimeout(800); await page.waitForSelector("#nav button", { state: "attached" }); await page.waitForTimeout(500);
ok(await count() === 0, "everything is gone after Delete everything");
ok(await page.evaluate(() => !localStorage.getItem("bl-items") || localStorage.getItem("bl-items") === "[]" || JSON.parse(localStorage.getItem("bl-items")).every((x) => x.example || x._id === "profile")), "no entries left in the quick copy");
ok(errs.length === 0, "no page errors" + (errs[0] ? ": " + errs[0] : ""));
await b.close(); srv.kill(); process.exit(fails.length ? 1 : 0);
