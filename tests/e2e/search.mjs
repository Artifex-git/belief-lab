import { chromium, devices } from "playwright-core";
import { spawn } from "node:child_process";
const srv = spawn("npx", ["vite", "preview", "--port", "4177", "--strictPort"], { stdio: "ignore" });
await new Promise((r) => setTimeout(r, 2500));
const fails = []; const ok = (c, m) => { console.log((c ? "PASS " : "FAIL ") + m); if (!c) fails.push(m); };
const b = await chromium.launch({ executablePath: process.env.CHROMIUM || "/usr/bin/chromium", args: ["--no-sandbox"] });
const ctx = await b.newContext({ ...devices["iPhone 13"] });
await ctx.addInitScript(() => { if (!localStorage.getItem("bl-items")) localStorage.setItem("bl-items", JSON.stringify([{ _id: "profile", kind: "profile", onboarded: true, created_at: 1 }, { _id: "e1", kind: "entry", created_at: Date.now(), belief_raw: "I never get enough rest", root: "worth" }])); });
const page = await ctx.newPage();
const errs = []; page.on("pageerror", (e) => errs.push(e.message));
await page.route("**/fonts.g*/**", (r) => r.abort());
await page.goto("http://localhost:4177/"); await page.waitForSelector("#nav button", { state: "attached" });
await page.evaluate(() => document.querySelector('[data-go="journey"]').click()); await page.waitForTimeout(300);
await page.fill("#jq", "rest"); await page.waitForTimeout(200);
ok((await page.textContent("#jres")).includes("never get enough rest"), "hit shown");
await page.screenshot({ path: "shots/08-search.png" });
await page.fill("#jq", "zzzz"); await page.waitForTimeout(200);
ok((await page.textContent("#jres")).includes("Nothing found"), "empty state");
ok(errs.length === 0, "no page errors" + (errs[0] ? ": " + errs[0] : ""));
await b.close(); srv.kill(); process.exit(fails.length ? 1 : 0);
